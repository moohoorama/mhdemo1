def rect(i, x, y, w, h, name, desc=''):
    return {'ID': i, 'Rect': {'X': x, 'Y': y, 'W': w, 'H': h}, 'Name': name, 'Description': desc}


def enemy(ch, x, y, group, **kw):
    e = {'Character': ch, 'X': x, 'Y': y, 'Group': group, 'Faction': 'wei', 'HPPct': 50}
    if group == 'road':
        e.update({'Policy': 'flee', 'GoalArea': 9})
    else:
        e.update({'Policy': 'hold'})
    if ch.startswith('troop_'):
        e['Shift'] = -0.07
    e.update(kw)
    return e


def say(actor, text):
    return {'Kind': 'say', 'Lines': [{'Actor': actor, 'Text': text}]}


def wait(sec):
    return {'Kind': 'cutscene', 'Steps': [[{'Kind': 'wait', 'Seconds': sec}]]}


