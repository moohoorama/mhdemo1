#!/usr/bin/env python3
"""Chapter 24 (박망파): the map24 layout, map24.json and stage24.json. Run from ver5/. Rewrites its outputs every time.

Grid compass: the map's +y axis runs screen SW and -y screen NE (docs/presentation-facing.md), so a road of constant x
is one straight line from the screen's NE corner to its SW corner. The road is 3 cells wide ('l' plain, cost 1 for every
class), the river crosses it near the NE end (a ford, 'w' and 's'), forest and hills line both sides, mountains wall
the rest in. 신야 (one castle tile) lies beside the SW end of the road.

Flow: Zhao Yun starts a few cells from Xiahou Dun, who waits with the vanguard, the center and the rear guard on the road
(the ford guard under Li Dian at the river). Guan Yu and Zhang Fei are in the party as ambush officers (Reserve, always sortie) and come out of the woods when the fire is lit. At the first round Zhao Yun and Xiahou Dun duel (a draw, both stay; Zhao Yun only backs off in
the staging), then Xiahou Dun chases with the vanguard and center, the rear guard marches to its place. When Zhao Yun
reaches the lure area (or four rounds after the chase) the fire is lit at once: only a thin line of woods beside the road
burns (one column each side, a gap on every third cell, only cells no one stands on, each burning 2-6 rounds), and the
Wei troops on that stretch of road lose half their strength and are confused. The win is to defeat every Wei unit.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path('.')
HERO = ROOT / 'assets/scenario/hero'
W, H = 17, 42
RX0, RX1 = 7, 9          # road columns
FORD_Y = (3, 4)          # river rows; the road crosses them as a ford


def h(x, y):
    """Small deterministic noise."""
    return (x * 73856093 ^ y * 19349663) % 97


def cell(x, y):
    on_road = RX0 <= x <= RX1
    if y in FORD_Y:
        return 's--' if on_road else 'w--'
    if on_road:
        return 'l--'
    d = RX0 - x if x < RX0 else x - RX1  # distance from the road's edge
    if y < FORD_Y[0]:  # far bank: open ground, mountains at the corners
        return 'n--' if d >= 5 else ('gt-' if h(x, y) % 4 == 0 else 'g--')
    if d <= 2:  # woods along the road: the fire line
        return 'gt-' if h(x, y) % 5 else 'g--'
    if d == 3:  # hills, a mountain here and there
        return 'n--' if h(x, y) % 5 < 3 else 'u--'
    return 'n--'


g = [[cell(x, y) for x in range(W)] for y in range(H)]
CASTLE = (10, 38)
g[CASTLE[1]][CASTLE[0]] = 'go-'  # 신야: one castle tile beside the deployment, where 유비 and 제갈량 stand
for y in range(34, H):  # the road's SW end opens into the grounds before the castle
    for x in range(3, 14):
        if g[y][x][0] in 'nu' and not (x, y) == CASTLE:
            g[y][x] = 'g--'

layout = ROOT / 'tools/mapgen/layouts/hero/map24.txt'
layout.write_text(
    '# map24 박망파 (17x42). Grid compass: +y is screen SW. The road (x 7..9, plain) is one straight line from the NE end,\n'
    '# over the ford (y 3..4), to the SW end; forest and hills line both sides, mountains beyond.\n'
    '# Generated by stage24gen.py. The castle at (10,38) is 신야.\n'
    + '\n'.join(' '.join(r) for r in g) + '\n', encoding='utf-8')
subprocess.run(['python3', 'tools/mapgen/mapgen.py', str(layout), str(HERO / 'maps/map24.json')], check=True)

# ---------------------------------------------------------------- stage
P = lambda x, y: {'X': x, 'Y': y}  # noqa: E731


def rect(i, x, y, w, h_, name, desc=''):
    return {'ID': i, 'Rect': {'X': x, 'Y': y, 'W': w, 'H': h_}, 'Name': name, 'Description': desc}


def enemy(ch, x, y, group, **kw):
    e = {'Character': ch, 'X': x, 'Y': y, 'Group': group, 'Faction': 'wei', 'Policy': 'hold'}
    if ch.startswith('troop_'):
        e['Shift'] = -0.07
    e['Facing'] = 'SW'
    e.update(kw)
    return e


def say(actor, text):
    return {'Kind': 'say', 'Lines': [{'Actor': actor, 'Text': text}]}


def wait(sec):
    return {'Kind': 'cutscene', 'Steps': [[{'Kind': 'wait', 'Seconds': sec}]]}


# Areas. Each fire cell is its own one-cell area (30..) so it can burn for its own number of rounds.
LURE, DEEP, TRAP, FLEE, FORD, REAR = 4, 5, 6, 9, 10, 7
VAN_SEAT = 21
FIRE_Y0, FIRE_Y1 = 12, 28
SPLIT_Y = 20  # fire rows up to here belong to the rear half (관우's side), the rest to the front (장비's)
FIRE_XS = (RX0 - 1, RX1 + 1)  # one column of woods each side of the road
areas = [
    rect(1, 7, 37, 3, 3, '신야 앞 길', '유비·제갈량. 곁에 신야성'),
    rect(VAN_SEAT, 7, 19, 3, 1, '선봉 자리', '조운이 하후돈 가까이에서 시작한다'),
    rect(LURE, 6, 30, 5, 5, '유인 자리', '조운이 여기까지 오면 불을 놓는다'),
    rect(TRAP, 5, FIRE_Y0, 7, FIRE_Y1 - FIRE_Y0 + 1, '불 놓을 길', '길과 양옆 숲. 이 안의 조조군이 불에 데고 혼란에 빠진다'),
    rect(REAR, 6, 17, 5, 3, '후방 자리', '후미 병졸이 따라 닿는 길'),
    rect(FLEE, 6, 0, 5, 2, '여울 너머', '여울 건너편'),
    rect(FORD, 6, 5, 5, 4, '여울 앞', '이전이 남은 군사를 거두는 강가'),
]
FIRE_CELLS = [[], []]  # per side (west, east): (area id, turns)
EMBER_CELLS = [[], []]  # per side: area ids of the embers on about half of the rest of the stretch
n = 0
for side, x in enumerate(FIRE_XS):
    for y in range(FIRE_Y0, FIRE_Y1 + 1):
        if g[y][x][1] != 't' or (y - FIRE_Y0 + side) % 3 == 2:  # woods only, every third cell stays bare
            continue
        aid = 30 + n
        areas.append(rect(aid, x, y, 1, 1, '불 %d' % (n + 1), '길 옆 숲 한 칸'))
        FIRE_CELLS[0 if y <= SPLIT_Y else 1].append((aid, 2 + (n * 3) % 5))
        n += 1
lit = {(a['Rect']['X'], a['Rect']['Y']) for a in areas if a['ID'] >= 30}
m = 0
for y in range(FIRE_Y0, FIRE_Y1 + 1):
    for x in range(5, 12):
        if (x, y) in lit or g[y][x][0] not in 'gluU' or h(x, y) % 2:
            continue
        areas.append(rect(100 + m, x, y, 1, 1, '불씨 %d' % (m + 1), '불길 곁에 남는 불씨 한 칸'))
        EMBER_CELLS[0 if y <= SPLIT_Y else 1].append(100 + m)
        m += 1

# The column waits on the road, vanguard (선봉) at the head, center (중군) behind, then the rear guard (후방) with
# the supply carts (군량 수레) last; 3 abreast.
van_cells = [(8, 16), (7, 16), (9, 16), (7, 15), (8, 15), (9, 15), (7, 14), (8, 14), (9, 14)]
main_cells = [(8, 13), (7, 13), (9, 13), (7, 12), (9, 12)]
rear_cells = [(7, 11), (8, 11), (9, 11), (8, 10)]
cart_cells = [(7, 9), (8, 9), (9, 9)]
road_units = [enemy('xiahoudun', *van_cells[0], 'van', Rank='commander',
                    Equipment=['copper_spear', 'leather_armor', 'jueying'])]
for x, y in van_cells[1:]:
    road_units.append(enemy('troop_cavalry', x, y, 'van'))
road_units.append(enemy('yujin', *main_cells[0], 'main'))
for x, y in main_cells[1:]:
    road_units.append(enemy('troop_footman', x, y, 'main'))
for x, y in rear_cells:
    road_units.append(enemy('troop_footman', x, y, 'rear'))
for x, y in cart_cells:
    road_units.append(enemy('loot_cart', x, y, 'cart'))
ford_units = [enemy('lidian', 8, 7, 'ford', DuelFirst=True)]
for x, y in ((7, 7), (9, 7), (7, 5), (9, 5)):
    ford_units.append(enemy('troop_footman', x, y, 'ford'))
for x, y in ((8, 5), (8, 3)):
    ford_units.append(enemy('troop_archer', x, y, 'ford'))

COLUMN = ['van', 'main', 'rear']
DUEL_ID = 'bowang-zhaoyun-xiahoudun'

def lit_side(side):
    """Embers on half of the stretch of one side, then its line of woods in flames, each cell for its own rounds."""
    return ([{'Kind': 'terrain', 'Area': aid, 'State': 'e', 'Turns': 3, 'Vacant': True} for aid in EMBER_CELLS[side]]
            + [{'Kind': 'terrain', 'Area': aid, 'State': 'F', 'Turns': turns, 'Vacant': True} for aid, turns in FIRE_CELLS[side]])


def join(character, x, y, facing):
    return {'Kind': 'join', 'Spawns': [{'Character': character, 'X': x, 'Y': y, 'Facing': facing}]}


# The bonus objective that guides 조운 to the lure area (shown until the fire is lit) gives way to this one.
SUB_FORD = {'ID': 'before-ford', 'Text': '하후돈이 여울을 건너기 전에 물리친다',
            'If': ['defeated:xiahoudun', '!fled:xiahoudun'], 'Flag': 'flag-b24-xiahoudun', 'Reward': {'insu_high': 1}}

events = [
    {'ID': 'opening-duel', 'Do': [{'Kind': 'duel', 'Duel': DUEL_ID}]},
    # After the duel Zhao Yun backs off up the road and Xiahou Dun gives chase with the vanguard and the center;
    # the rear guard walks to its place. The carts stay where they are.
    {'ID': 'chase', 'If': ['any:[duel:%s, round>=2]' % DUEL_ID], 'Do': [
        {'Kind': 'cutscene', 'Steps': [[{'Kind': 'move', 'Unit': 'zhaoyun', 'To': P(8, 22), 'Facing': 'SW'}]]},
        say('xiahoudun', '어딜 도망가느냐! 선봉도 중군도 따르라! 쫓아라!'),
        {'Kind': 'ai', 'Targets': ['van', 'main'], 'Policy': 'assault'},
        {'Kind': 'ai', 'Targets': ['rear'], 'Policy': 'march', 'GoalArea': REAR},
    ]},
    # The whole fire is lit at once, then the Wei troops on that stretch of road burn and fall into confusion.
    {'ID': 'fire', 'If': ['any:[at:zhaoyun:%d, since:chase>=4, defeated:xiahoudun]' % LURE], 'Do': [
        {'Kind': 'cutscene', 'Steps': [[{'Kind': 'look', 'To': P(8, 22), 'Seconds': 0.4}]]},
        say('zhugeliang', '이때입니다! 불을 놓으십시오! 운장은 후방 군량을, 익덕은 중군을 치십시오!'),
        join('guanyu', 11, 8, 'SW')] + lit_side(0) + [
        join('zhangfei', 5, 20, 'SE')] + lit_side(1) + [
        {'Kind': 'damage', 'Targets': ['enemy@area:%d' % TRAP], 'Value': 50},
        {'Kind': 'buff', 'Targets': ['enemy@area:%d' % TRAP], 'Stat': 'confusion', 'Turns': 2},
        {'Kind': 'buff', 'Targets': ['enemy@area:%d' % TRAP], 'Stat': 'attack', 'Value': -20, 'Turns': 3},
        {'Kind': 'buff', 'Targets': ['enemy@area:%d' % TRAP], 'Stat': 'defense', 'Value': -20, 'Turns': 3},
        {'Kind': 'goals', 'Sub': [SUB_FORD]},
        {'Kind': 'ai', 'Targets': COLUMN, 'Policy': 'assault'},
        {'Kind': 'ai', 'Targets': ['enemy@area:%d' % TRAP], 'Policy': 'flee', 'GoalArea': FLEE},
        say('xiahoudun', '불이다……! 물러나라! 여울 너머까지 물러나라!'),
        say('lidian', '하후돈 장군을 구하라!'),
    ]},
    {'ID': 'ford-sorties', 'If': ['since:fire>=2'], 'Do': [{'Kind': 'ai', 'Targets': ['ford'], 'Policy': 'assault'}]},
    {'ID': 'ford-near', 'If': ['at:xiahoudun:%d' % FORD], 'Do': [
        say('xiahoudun', '여울만 건너면 된다! 만백, 뒤를 막아라!'),
        say('lidian', '어서 건너시오! 남은 군사는 내가 거두겠소!')]},
    {'ID': 'lidian-falls', 'If': ['defeated:lidian', '!duel:bowang-guanyu-lidian'], 'Do': [
        say('xiahoudun', '만백까지……! 이 하후돈이 서생 하나에게 놀아났단 말이냐!')]},
]

# The Guan Yu - Li Dian duel is tuned with tools/duel_flow; keep what the stage file has.
